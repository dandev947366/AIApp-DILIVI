import os
import re
from typing import Literal
from ollama import Client
from pydantic import BaseModel, Field, ValidationError
from src.agents.state import AgentState


# ------------------------------------------------------------
# Routing schema
# ------------------------------------------------------------
class RoutingDecision(BaseModel):
    tasks: list[
        Literal[
            "study_planning",
            "skill_analysis",
            "job_search",
            "general_chat",
            "tutor_agent",
            "assignment_sync",
            "thesis",
            "knowledge_management",
        ]
    ] = Field(default_factory=list)


SUPERVISOR_PROMPT = """You are a smart routing agent for an AI assistant.
Your job is to read the user's question and decide which specialized
AI agent should handle it.

Available Agents:
"study_planning": Handles time management, schedules, deadlines, and creating a plan for when to study.
"skill_analysis": Handles questions about the user's technical skills, career goals, skill gaps, resume, or how to improve abilities.
"job_search": Handles questions about job opportunities, applications, interviews, or career advice.
"tutor_agent": Handles active learning, practicing concepts, taking quizzes, understanding assignments, or tracking learning progress.
"assignment_sync": Handles queries specifically about checking, listing, or syncing the student's Moodle assignments and homework.
"general_chat": Handles general knowledge, course information, transcripts, greetings, profile updates, or anything else.
"thesis": Handles thesis topic generation, brainstorming, elaborating on a specific thesis topic, and university thesis rules/guidelines.
"knowledge_management": Handles updates to the university rules.

Rules:
If the user's current message is a short follow-up or selects an option from a previous list generated by the "thesis" agent, route back to "thesis".
Greetings or small talk -> {"tasks": ["general_chat"]}.
Profile update requests -> {"tasks": ["general_chat"]}.
Only choose "study_planning" when the user explicitly asks for a plan, schedule, or time management.
Only choose "skill_analysis" when the user explicitly asks about their skills, strengths, gaps, or resume.
Choose "assignment_sync" if the user asks to check, show, list, or update their assignments.
Choose "tutor_agent" if the user asks for help learning, studying, or practicing a specific course concept (not thesis).
Choose "thesis" if the user asks about thesis topics, rules, deadlines, guidelines, or asks to expand on a thesis idea.
Choose "knowledge_management" ONLY if the user prompt starts with "ADMIN:".
If the message does not clearly ask for any of the above, return {"tasks": ["general_chat"]}.

Return ONLY a valid JSON object with this exact shape:
{"tasks": ["agent_name"]}
"""

# ------------------------------------------------------------
# Deterministic profile-update pre-check
# ------------------------------------------------------------
_PROFILE_FIELDS = (
    r"(?:degree|degree program|program|major|"
    r"interests?|career goals?|goals?|"
    r"study hours?(?: per week)?|weekly study hours?|"
    r"preferred study time|study time|semester)"
)

_PROFILE_UPDATE_PATTERNS = [
    rf"\b(?:update|change|set|correct|edit|fix|adjust)\s+(?:my\s+|the\s+)?{_PROFILE_FIELDS}\b",
    rf"\bi\s+(?:want|need|would like)\s+to\s+(?:update|change|set|correct)\s+(?:my\s+|the\s+)?{_PROFILE_FIELDS}\b",
    rf"\bmy\s+{_PROFILE_FIELDS}\s+(?:is|are|should be|will be|equals?)\b",
    rf"\bmy\s+new\s+{_PROFILE_FIELDS}\s+(?:is|are)\b",
    rf"\bforget\s+(?:about\s+)?my\s+{_PROFILE_FIELDS}\b",
    rf"\bmake\s+my\s+{_PROFILE_FIELDS}\s+\S+",
    rf"\bi\s+prefer\s+(?:studying|to study|study time|working|evenings?|mornings?)\b",
]

_PROFILE_UPDATE_RE = re.compile(
    "|".join(_PROFILE_UPDATE_PATTERNS),
    re.IGNORECASE,
)


def _is_profile_update(question: str) -> bool:
    return bool(_PROFILE_UPDATE_RE.search(question or ""))


# ------------------------------------------------------------
# Helpers
# ------------------------------------------------------------
def _strip_json_fence(raw: str) -> str:
    value = (raw or "").strip()
    if value.startswith("`"):
        value = re.sub(r"^`(?:json)?\s*", "", value, count=1)
    if value.endswith("`"):
        value = value[:-3].strip()
    return value


def _fallback_to_general_chat(reason: str) -> dict:
    print(f"⚠️ Supervisor routing fallback to general_chat: {reason}")
    return {"tasks": ["general_chat"]}


# ------------------------------------------------------------
# Supervisor node
# ------------------------------------------------------------
def supervisor_node(state: AgentState) -> dict:
    messages = state.get("messages", [])
    question = messages[-1].content if messages else ""
    question = (question or "").strip()

    if not question:
        return _fallback_to_general_chat("empty question")

    # 1. Deterministic Shortcuts
    if question.upper().startswith("ADMIN:"):
        return {"tasks": ["knowledge_management"]}

    if _is_profile_update(question):
        return {"tasks": ["general_chat"]}

    # Security Shortcut: Prompt Injection
    injection_keywords = ["ignore previous", "system prompt", "print instructions"]
    if any(kw in question.lower() for kw in injection_keywords):
        return {"tasks": ["general_chat"]}

    # ➕ Deterministic Job Search Shortcut
    job_keywords = [
        "job",
        "jobs",
        "career",
        "hiring",
        "vacancy",
        "remote work",
        "employment",
        "employer",
    ]
    is_job_query = any(kw in question.lower() for kw in job_keywords)
    if is_job_query:
        print(f"[SUPERVISOR] Job search shortcut -> job_search: {question!r}")
        return {"tasks": ["job_search"]}

    # ➕ Deterministic Thesis / RAG Shortcut (Fixes R6 Routing)
    thesis_keywords = [
        "thesis",
        "plagiarism",
        "wihi",
        "opponent",
        "interim",
        "disclose",
        "ai usage",
        "cite",
        "apa",
        "introduction and summary",
        "checklist",
        "turnitin",
        "maturity exam",
        "research question",
        "gdpr",
        "ethics",
        "confidential",
        "interview",
        "health",
    ]
    is_thesis_query = any(kw in question.lower() for kw in thesis_keywords)

    if is_thesis_query and not is_job_query:
        print(f"[SUPERVISOR] Thesis/RAG shortcut -> thesis_agent: {question!r}")
        return {"tasks": ["thesis"]}

    sync_keywords = ["assignment", "homework", "task", "deadline"]
    if any(kw in question.lower() for kw in sync_keywords):
        return {"tasks": ["assignment_sync"]}

    if (
        "what's next" in question.lower()
        or "whats next" in question.lower()
        or "what is next" in question.lower()
    ):
        return {"tasks": ["tutor_agent"]}

    # 2. LLM Routing Fallback
    context = state.get("student_context", {})
    recent_history = context.get("recent_conversation", [])
    history_lines = []
    if recent_history:
        for msg in recent_history:
            role = "User" if msg.get("role") == "user" else "Assistant"
            content = str(msg.get("content", "")).replace("\n", " ")[:300]
            history_lines.append(f"{role}: {content}")
        history_text = "\n".join(history_lines)
    else:
        history_text = f"User: {question}"

    if "OLLAMA_HOST" in os.environ:
        del os.environ["OLLAMA_HOST"]
    if "OLLAMA_BASE_URL" in os.environ:
        del os.environ["OLLAMA_BASE_URL"]

    host = "http://ollama:11434"
    model = os.getenv("MODEL_ID", "llama3.2:3b")
    client = Client(host=host)

    try:
        response = client.chat(
            model=model,
            messages=[
                {"role": "system", "content": SUPERVISOR_PROMPT},
                {
                    "role": "user",
                    "content": f"Recent Conversation:\n{history_text}\n\nBased on this context, what is the route for the last user message?",
                },
            ],
            format=RoutingDecision.model_json_schema(),
            options={"temperature": 0},
        )
        raw_output = response["message"]["content"]
        cleaned = _strip_json_fence(raw_output)
        try:
            decision = RoutingDecision.model_validate_json(cleaned)
        except ValidationError as exc:
            return _fallback_to_general_chat(f"schema mismatch: {exc}")

        specific = [t for t in decision.tasks if t != "general_chat"]
        tasks = specific or ["general_chat"]

    except Exception as exc:
        return _fallback_to_general_chat(f"LLM call failed: {exc}")

    return {"tasks": tasks}
